// Inlines assets/donation-qr.png into src/qr.ts as a base64 data URL.
// Community installs only ship main.js / manifest.json / styles.css, so the image
// cannot be loaded from disk at runtime. Run: node scripts/make-qr.mjs
import { readFileSync, writeFileSync } from "node:fs";

const png = readFileSync(new URL("../assets/donation-qr.png", import.meta.url));
const dataUrl = `data:image/png;base64,${png.toString("base64")}`;

const out = `// Generated by scripts/make-qr.mjs from assets/donation-qr.png — do not edit by hand.
// The image is inlined because community installs ship only main.js / manifest.json / styles.css.
export const DONATION_QR_DATA_URL =
  "${dataUrl}";
`;

writeFileSync(new URL("../src/qr.ts", import.meta.url), out);
console.log(`src/qr.ts written, ${dataUrl.length} characters`);
